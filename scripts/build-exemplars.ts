/**
 * Builds config/human-exemplars.ts: the pool of real human-written passages that the rewrite
 * prompt shows the model as reference for how a person's sentences move.
 *
 *   pnpm exemplars:build                       rebuild from the built-in public-domain sources
 *   pnpm exemplars:build --own bench/my-writing --register neutral
 *                                              add your own .txt files (kept in front of the defaults)
 *   pnpm exemplars:build --only-own bench/my-writing   use ONLY your own writing
 *
 * Passages are cut out of the source files by this script, word for word. Do not type or generate
 * passages by hand: text written by a model teaches the model to write like a model.
 *
 * A passage must be 45-95 words, at most 480 characters, start at a sentence start, and have no
 * dialogue, markup, headings or number-heavy text. Your own writing should be modern, plain, and
 * free of typos, because the model imitates whatever it is shown.
 */
import fs from "fs";
import path from "path";
import { extractPassages } from "../lib/ai/extractPassages";

type Register = "casual" | "neutral" | "formal";
type Source = { file: string; register: Register; source: string; take: number; skip?: boolean };

const DEFAULT_SOURCES: Source[] = [
  // Plain narrative and expository prose, Albert Bigelow Paine, "Mark Twain: A Biography" (public domain)
  // (05-personaA is a whimsical comic monologue, not a model for ordinary expository writing, so it is left out.)
  ...["02", "03", "04", "06"].map((n) => ({ file: `fixtures/target-voice/${n}-personaA.txt`, register: "neutral" as Register, source: "Paine, Mark Twain: A Biography (public domain)", take: 1 })),
  // Plain business prose from early 20th-century advertising texts (public domain)
  ...["01", "02", "03", "04"].map((n) => ({ file: `fixtures/genres/${n}-marketing.txt`, register: "neutral" as Register, source: "early 1900s advertising text (public domain)", take: 1 })),
  // Formal Victorian science writing, T. H. Huxley (public domain)
  ...["07", "08", "09", "10"].map((n) => ({ file: `fixtures/target-voice/${n}-personaB.txt`, register: "formal" as Register, source: "Huxley, Collected Essays (public domain)", take: 2 })),
];

const wc = (s: string) => s.split(/\s+/).filter(Boolean).length;

function listTxt(dir: string): string[] {
  return fs.readdirSync(dir).filter((f) => f.endsWith(".txt")).sort().map((f) => path.join(dir, f));
}

const argv = process.argv.slice(2);
const opt = (name: string) => { const i = argv.indexOf(`--${name}`); return i >= 0 ? argv[i + 1] : undefined; };
const ownDir = opt("own") ?? opt("only-own");
const onlyOwn = argv.includes("--only-own");
const ownRegister = (opt("register") ?? "neutral") as Register;
if (!["casual", "neutral", "formal"].includes(ownRegister)) { console.error("--register must be casual, neutral or formal"); process.exit(1); }

const sources: Source[] = [];
if (ownDir) {
  if (!fs.existsSync(ownDir)) { console.error(`Folder not found: ${ownDir}`); process.exit(1); }
  for (const f of listTxt(ownDir)) sources.push({ file: f, register: ownRegister, source: "own writing", take: 2 });
}
if (!onlyOwn) sources.push(...DEFAULT_SOURCES);

const pool: { id: string; register: Register; source: string; text: string }[] = [];
for (const s of sources) {
  if (!fs.existsSync(s.file)) { console.warn(`skip (missing): ${s.file}`); continue; }
  const passages = extractPassages(fs.readFileSync(s.file, "utf8"), s.take);
  if (!passages.length) console.warn(`no usable passage in ${s.file}`);
  passages.forEach((text, k) => pool.push({ id: `${path.basename(s.file, ".txt")}${k ? `#${k + 1}` : ""}`, register: s.register, source: s.source, text }));
}
if (pool.length < 3) { console.error(`Only ${pool.length} passages found; need at least 3.`); process.exit(1); }

const body = pool.map((p) => `  { id: ${JSON.stringify(p.id)}, register: ${JSON.stringify(p.register)}, source: ${JSON.stringify(p.source)},\n    text: ${JSON.stringify(p.text)} },`).join("\n");
fs.writeFileSync("config/human-exemplars.ts", `/**
 * GENERATED by scripts/build-exemplars.ts. Do not edit by hand and do not add text a model wrote.
 * Real human-written passages shown to the model as a reference for how a person's sentences move.
 * To use your own writing: pnpm exemplars:build --own <folder of .txt files> --register casual
 */
export type HumanExemplar = { id: string; register: "casual" | "neutral" | "formal"; source: string; text: string };

export const HUMAN_EXEMPLARS: HumanExemplar[] = [
${body}
];
`);
console.log(`Wrote config/human-exemplars.ts with ${pool.length} passages:`);
for (const p of pool) console.log(`  [${p.register}] ${p.id.padEnd(22)} ${wc(p.text)}w  ${p.text.slice(0, 70)}...`);
